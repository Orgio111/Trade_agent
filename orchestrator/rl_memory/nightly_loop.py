"""
Offline Nightly Training Loop — cron job for daily RL improvement.

Runs every night (e.g., 02:00 UTC):
1. Pulls all trades from Postgres (last 24h or configurable window)
2. Replays through backtest engine with simulated RL updates
3. Computes aggregate rewards and identifies patterns
4. Generates policy update prompt for LLM
5. Updates strategy rules / agent prompts
6. Logs metrics and saves policy version
"""

